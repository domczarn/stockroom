import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import vm from 'node:vm';
import {validateWorkspace} from '../worker/security.js';
const context=vm.createContext({Date});vm.runInContext(readFileSync('web/customer.js','utf8'),context);
const ready=(trade,order,step,now)=>context.careReady(trade,order,step,new Date(now||'2026-11-07T12:00:00Z'));
const trade={soldAt:'2026-11-01',refunds:[]};
assert.equal(ready(trade,{},'thanks'),true);
assert.equal(ready(trade,{},'posted'),false);
assert.equal(ready({...trade,postedAt:'2026-11-02'},{},'posted'),true);
assert.equal(ready({...trade,completedAt:'2026-11-03'},{},'delivered'),false);
assert.equal(ready(trade,{deliveredAt:'2026-11-06'},'followup'),false);
assert.equal(ready(trade,{deliveredAt:'2026-11-03'},'followup'),true);
assert.equal(ready({...trade,refunds:[{amount:10}]},{deliveredAt:'2026-11-03'},'thanks'),false);
assert.equal(context.careDraft('Hi {buyer}: {item}. {tracking}',{buyer:'A',item:'<hoodie>',tracking:''}),'Hi A: <hoodie>. ');
const base={items:[],sales:[],expenses:[],research:[],sources:[],customerCare:{shop:'Shop',templates:{thanks:'Hi {buyer}'},orders:{}}};
assert.equal(validateWorkspace(base,'owner'),base);
assert.throws(()=>validateWorkspace({...base,customerCare:{...base.customerCare,orders:{foreign:{buyer:'A'}}}},'owner'));
assert.throws(()=>validateWorkspace({...base,customerCare:{...base.customerCare,templates:{thanks:'x'.repeat(3001)}}},'owner'));
console.log('Customer journey gates, refunds, interpolation and workspace validation passed');
